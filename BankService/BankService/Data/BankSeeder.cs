
using BankService.Models;
using BankService.Services;
using Microsoft.EntityFrameworkCore;
using System.Runtime.CompilerServices;

// MEMBER 1 - REQUIREMENT 5
// Allow the MSTest project to test internal seed generation
// without exposing it as a public application API.
[assembly: InternalsVisibleTo("BankService.Tests")]

namespace BankService.Data
{
    // =====================================================
    // MEMBER 1 - REQUIREMENT 5: AUTOMATIC DATA SEEDING
    // =====================================================
    //
    // Purpose:
    // Generate the initial demonstration banking data:
    // 20 users, 30 accounts and 500 transactions.
    //
    // Assignment reference:
    // Assignment 2 Part A - Requirement 5.
    //
    // Lecturer reference:
    // Database-DC-Web lectures - Entity Framework Core.
    //
    // External reference:
    // Microsoft Learn - EF Core Data Seeding
    // https://learn.microsoft.com/en-us/ef/core/modeling/data-seeding
    //
    // Design:
    // Build all records first, then persist them using
    // one database transaction in a later step.
    //
    // IMPORTANT:
    // This is demonstration data, not production data.
    // =====================================================

    public static class BankSeeder
    {
        private const int UserCount = 20;
        private const int AccountCount = 30;
        private const int TransactionCount = 500;

        // -------------------------------------------------
        // STEP 1 - GENERATE 20 DEMONSTRATION USERS
        // -------------------------------------------------
        //
        // Each user receives:
        // - A unique username and email address.
        // - A hashed and salted password.
        // - An active account status.
        // - A Customer or Admin role.
        //
        // The first user is assigned the Admin role to
        // support administrator functionality testing.
        //
        // Passwords below are predictable only because
        // these are controlled demonstration accounts.
        // Never use these credentials in production.

        private static List<User> CreateUsers(
            PasswordService passwordService)
        {
            var users = new List<User>();

            for (int i = 1; i <= UserCount; i++)
            {
                string suffix = i.ToString("D2");

                // Create a separate demonstration password
                // for each user and securely hash it.
                string demoPassword =
                    $"DemoUser{suffix}!2026";

                var (hash, salt) =
                    passwordService.HashPassword(demoPassword);

                var user = new User
                {
                    Username = $"seeduser{suffix}",

                    Name = i == 1
                        ? "Demo Administrator"
                        : $"Demo Customer {suffix}",

                    Email = $"seeduser{suffix}@example.test",
                    Address = $"Demo Address {suffix}",
                    Phone = $"0123456{i:D4}",

                    PicturePath = string.Empty,

                    PasswordHash = hash,
                    PasswordSalt = salt,

                    Role = i == 1 ? "Admin" : "Customer",
                    IsActive = true
                };

                users.Add(user);
            }

            return users;
        }


        // -------------------------------------------------
        // MEMBER 1 - REQUIREMENT 5
        // STEP 2 - GENERATE 30 BANK ACCOUNTS
        // -------------------------------------------------
        //
        // Purpose:
        // Create 30 bank accounts belonging to the
        // 20 users generated by CreateUsers().
        //
        // Assignment reference:
        // Assignment 2 Part A - Requirement 5.
        //
        // Lecturer reference:
        // Database-DC-Web lectures - EF Core relationships.
        //
        // External reference:
        // Microsoft Learn - EF Core Relationships
        // https://learn.microsoft.com/en-us/ef/core/modeling/relationships
        //
        // Design:
        // - Every user must own at least one account.
        // - The first 10 users receive two accounts.
        // - Every account number must be unique.
        // - Every account begins with a zero balance.
        // - Account balances will be updated when
        //   transactions are generated in Step 3.
        //
        // Important:
        // Link Account.User directly to the User object.
        // EF Core will populate Account.UserId when
        // the related records are saved.

        private static List<Account> CreateAccounts(
            List<User> users)
        {
            var accounts = new List<Account>();

            for (int i = 1; i <= AccountCount; i++)
            {
                // Distribute 30 accounts among 20 users.
                //
                // Accounts 1-20:
                // One account for each user.
                //
                // Accounts 21-30:
                // A second account for users 1-10.
                int userIndex = (i - 1) % users.Count;

                User owner = users[userIndex];

                // Generate a unique demonstration
                // account number with a fixed prefix.
                string accountNumber = $"8000{i:D6}";

                var account = new Account
                {
                    AccountNumber = accountNumber,

                    // All balances begin at zero.
                    // Deposits will establish initial funds
                    // during transaction generation.
                    Balance = 0.00m,

                    IsActive = true,

                    // Link this account to its owner.
                    User = owner
                };

                accounts.Add(account);
            }

            return accounts;
        }


        // -------------------------------------------------
        // MEMBER 1 - REQUIREMENT 5
        // STEP 3 - GENERATE 500 BANKING TRANSACTIONS
        // -------------------------------------------------
        //
        // Purpose:
        // Generate valid deposits, withdrawals and transfers
        // while maintaining consistent account balances.
        //
        // Assignment reference:
        // Assignment 2 Part A - Requirement 5.
        //
        // Lecturer references:
        // Database-DC-Web lectures - Database relationships.
        // Tutorial 6 - Banking transaction concepts.
        //
        // Design:
        // - Generate exactly 500 transaction records.
        // - Give all 30 accounts an initial deposit.
        // - Use decimal values for monetary calculations.
        // - Prevent withdrawals and transfers from
        //   exceeding the available account balance.
        // - Update both accounts involved in a transfer.
        // - Generate transactions in chronological order.
        //
        // Important:
        // Transfers use ONE transaction record, with
        // Account as the source and TargetAccount as
        // the receiving account. This matches the
        // current Transaction model.

        private static List<Transaction> CreateTransactions(
            List<Account> accounts)
        {
            if (accounts.Count != AccountCount)
            {
                throw new ArgumentException(
                    "Exactly 30 accounts are required.");
            }

            var transactions = new List<Transaction>();

            // Fixed seed makes the demonstration amounts
            // reproducible. It is not used for passwords.
            var random = new Random(2026);

            // Begin the transaction history 30 days ago.
            DateTime startTime = DateTime.UtcNow.AddDays(-30);

            // ---------------------------------------------
            // PART A - INITIAL DEPOSITS FOR ALL 30 ACCOUNTS
            // ---------------------------------------------
            //
            // Each account receives between $1,000 and
            // $3,000 before other transactions begin.
            //
            // This ensures that all accounts have funds
            // available for subsequent transactions.

            for (int i = 0; i < accounts.Count; i++)
            {
                Account account = accounts[i];

                // Generate a monetary value with 2
                // decimal places.
                decimal amount =
                    random.Next(100_000, 300_001) / 100m;

                // Deposit increases the account balance.
                account.Balance += amount;

                var transaction = new Transaction
                {
                    TimeStamp = startTime.AddHours(i),
                    Amount = amount,
                    Type = "Deposit",
                    Description = "Initial account deposit",

                    // Establish the source account
                    // relationship through navigation.
                    Account = account
                };

                transactions.Add(transaction);
            }

            // ---------------------------------------------
            // PART B - GENERATE THE REMAINING TRANSACTIONS
            // ---------------------------------------------
            //
            // Generate deposits, withdrawals and transfers.
            //
            // If insufficient funds exist for a withdrawal
            // or transfer, generate a deposit instead.
            //
            // This guarantees 500 valid transactions
            // without overdrawing any account.

            for (int i = accounts.Count;
                 i < TransactionCount;
                 i++)
            {
                // Select a random source account.
                int sourceIndex = random.Next(accounts.Count);
                Account source = accounts[sourceIndex];

                // Generate an amount between $10 and $500.
                decimal amount =
                    random.Next(1_000, 50_001) / 100m;

                // Rotate through three transaction types.
                string type = (i % 3) switch
                {
                    0 => "Deposit",
                    1 => "Withdrawal",
                    _ => "Transfer"
                };

                // Prevent a negative account balance.
                if ((type == "Withdrawal" ||
                     type == "Transfer") &&
                    source.Balance < amount)
                {
                    type = "Deposit";
                }

                Account? target = null;

                // -----------------------------------------
                // DEPOSIT
                // -----------------------------------------
                if (type == "Deposit")
        {
                    source.Balance += amount;
                }

                // -----------------------------------------
                // WITHDRAWAL
                // -----------------------------------------
                else if (type == "Withdrawal")
            {
                    source.Balance -= amount;
            }

                // -----------------------------------------
                // TRANSFER
                // -----------------------------------------
                else if (type == "Transfer")
                {
                    // Select a different target account.
                    int targetIndex =
                        random.Next(accounts.Count - 1);

                    if (targetIndex >= sourceIndex)
            {
                        targetIndex++;
                    }

                    target = accounts[targetIndex];

                    // Money leaves the source account.
                    source.Balance -= amount;

                    // The same amount enters the target.
                    target.Balance += amount;
            }

                // -----------------------------------------
                // CREATE TRANSACTION RECORD
                // -----------------------------------------
                var transaction = new Transaction
                {
                    TimeStamp = startTime.AddHours(i),
                    Amount = amount,
                    Type = type,

                    Description = type switch
            {
                        "Deposit" => "Demo deposit",
                        "Withdrawal" => "Demo withdrawal",
                        "Transfer" => "Demo bank transfer",
                        _ => "Demo transaction"
                    },

                    Account = source
            };

                // Only transfers have a target account.
                if (target != null)
                {
                    transaction.TargetAccount = target;
                }

                transactions.Add(transaction);
            }

            return transactions;
        }


        // -------------------------------------------------
        // MEMBER 1 - REQUIREMENT 5
        // STEP 4 - VALIDATE GENERATED BANKING DATA
        // -------------------------------------------------
        //
        // Purpose:
        // Verify that all generated users, accounts and
        // transactions satisfy the assignment's rules.
        //
        // Assignment reference:
        // Assignment 2 Part A - Requirement 5.
        //
        // Lecturer references:
        // Database-DC-Web lectures - Data relationships.
        // Tutorial 6 - Banking transaction concepts.
        //
        // Design:
        // Recalculate account balances independently
        // from the transaction history, starting at zero.
        //
        // This ensures that account balances are not
        // merely trusted because the generator assigned
        // them directly.
        //
        // Any invalid data causes an exception so that
        // the seeding process can stop before saving.

        private static void ValidateSeedData(
            List<User> users,
            List<Account> accounts,
            List<Transaction> transactions)
        {
            // ---------------------------------------------
            // STEP 4A - VALIDATE RECORD COUNTS
            // ---------------------------------------------

            if (users.Count != UserCount ||
                accounts.Count != AccountCount ||
                transactions.Count != TransactionCount)
            {
                throw new InvalidOperationException(
                    "Seed data contains incorrect record counts.");
            }

            // ---------------------------------------------
            // STEP 4B - CHECK UNIQUE USER INFORMATION
            // ---------------------------------------------

            if (users.Any(u =>
                    string.IsNullOrWhiteSpace(u.Username) ||
                    string.IsNullOrWhiteSpace(u.Email) ||
                    string.IsNullOrWhiteSpace(u.PasswordHash) ||
                    string.IsNullOrWhiteSpace(u.PasswordSalt)))
            {
                throw new InvalidOperationException(
                    "A generated user has missing information.");
            }

            if (users.Select(u => u.Username)
                     .Distinct(StringComparer.OrdinalIgnoreCase)
                     .Count() != UserCount)
            {
                throw new InvalidOperationException(
                    "Duplicate usernames detected.");
            }

            if (users.Select(u => u.Email)
                     .Distinct(StringComparer.OrdinalIgnoreCase)
                     .Count() != UserCount)
            {
                throw new InvalidOperationException(
                    "Duplicate email addresses detected.");
            }

            // ---------------------------------------------
            // STEP 4C - VALIDATE ACCOUNT RELATIONSHIPS
            // ---------------------------------------------

            var userSet = new HashSet<User>(users);

            if (accounts.Any(a =>
                    string.IsNullOrWhiteSpace(a.AccountNumber) ||
                    a.User == null ||
                    !userSet.Contains(a.User)))
            {
                throw new InvalidOperationException(
                    "Invalid account or user relationship.");
            }

            if (accounts.Select(a => a.AccountNumber)
                        .Distinct(StringComparer.Ordinal)
                        .Count() != AccountCount)
            {
                throw new InvalidOperationException(
                    "Duplicate account numbers detected.");
            }

            // Ensure every generated user owns an account.
            if (users.Any(u =>
                    !accounts.Any(a =>
                        ReferenceEquals(a.User, u))))
            {
                throw new InvalidOperationException(
                    "A generated user has no bank account.");
            }

            // ---------------------------------------------
            // STEP 4D - VALIDATE INITIAL DEPOSITS
            // ---------------------------------------------

            // The first 30 transactions must be deposits,
            // with one deposit belonging to each account.

            var initialDeposits = transactions
                .Take(AccountCount)
                .ToList();

            if (initialDeposits.Any(t => t.Type != "Deposit") ||
                initialDeposits.Select(t => t.Account)
                               .Distinct()
                               .Count() != AccountCount)
            {
                throw new InvalidOperationException(
                    "Initial account deposits are invalid.");
            }

            // ---------------------------------------------
            // STEP 4E - REBUILD BALANCES FROM TRANSACTIONS
            // ---------------------------------------------

            // Independent running balances begin at zero.
            // Account objects are used as dictionary keys
            // because their database IDs are not assigned.

            var calculatedBalances = accounts
                .ToDictionary(a => a, a => 0.00m);

            DateTime? previousTimestamp = null;

            foreach (var transaction in transactions)
            {
                // Confirm the transaction source exists.
                if (transaction.Account == null ||
                    !calculatedBalances.ContainsKey(
                        transaction.Account))
                {
                    throw new InvalidOperationException(
                        "Transaction has an invalid source account.");
                }

                // Transaction amounts must be positive
                // and have no more than two decimal places.
                if (transaction.Amount <= 0m ||
                    decimal.Round(transaction.Amount, 2)
                        != transaction.Amount)
                {
                    throw new InvalidOperationException(
                        "Invalid transaction amount.");
                }

                // Verify chronological generation order.
                if (previousTimestamp.HasValue &&
                    transaction.TimeStamp < previousTimestamp.Value)
                {
                    throw new InvalidOperationException(
                        "Transactions are not chronological.");
                }

                previousTimestamp = transaction.TimeStamp;

                Account source = transaction.Account;
                decimal amount = transaction.Amount;

                switch (transaction.Type)
                {
                    // -------------------------------------
                    // DEPOSIT: ADD MONEY TO SOURCE
                    // -------------------------------------
                    case "Deposit":

                        if (transaction.TargetAccount != null)
                        {
                            throw new InvalidOperationException(
                                "Deposit must not have a target account.");
                        }

                        calculatedBalances[source] += amount;
                        break;

                    // -------------------------------------
                    // WITHDRAWAL: SUBTRACT FROM SOURCE
                    // -------------------------------------
                    case "Withdrawal":

                        if (transaction.TargetAccount != null)
                        {
                            throw new InvalidOperationException(
                                "Withdrawal must not have a target account.");
                        }

                        calculatedBalances[source] -= amount;
                        break;

                    // -------------------------------------
                    // TRANSFER: MOVE MONEY BETWEEN ACCOUNTS
                    // -------------------------------------
                    case "Transfer":

                        Account? target =
                            transaction.TargetAccount;

                        if (target == null ||
                            !calculatedBalances.ContainsKey(target) ||
                            ReferenceEquals(source, target))
                        {
                            throw new InvalidOperationException(
                                "Transfer has an invalid target account.");
                        }

                        calculatedBalances[source] -= amount;
                        calculatedBalances[target] += amount;
                        break;

                    default:
                        throw new InvalidOperationException(
                            "Unknown transaction type.");
                }

                // Reject any transaction that would
                // cause an account to become overdrawn.
                if (calculatedBalances[source] < 0m)
                {
                    throw new InvalidOperationException(
                        "Transaction caused a negative balance.");
                }
            }

            // ---------------------------------------------
            // STEP 4F - COMPARE FINAL ACCOUNT BALANCES
            // ---------------------------------------------

            foreach (var account in accounts)
            {
                decimal expectedBalance =
                    calculatedBalances[account];

                if (account.Balance != expectedBalance)
                {
                    throw new InvalidOperationException(
                        $"Balance mismatch for account " +
                        $"{account.AccountNumber}.");
                }
            }

            // If no exception was thrown, the generated
            // data passed all of the checks above.
        }


        // -------------------------------------------------
        // MEMBER 1 - REQUIREMENT 5
        // STEP 6 - BUILD AND VALIDATE DATA FOR TESTING
        // -------------------------------------------------
        //
        // Purpose:
        // Combine the existing generation methods into
        // one testable operation.
        //
        // The method is internal, so it can be accessed
        // by BankService.Tests through InternalsVisibleTo.
        //
        // No database connection is required.
        //
        // Design:
        // Both automated tests and SeedAsync() should
        // use the same validated data generation logic.

        internal static (
            List<User> Users,
            List<Account> Accounts,
            List<Transaction> Transactions)
            GenerateValidatedData()
        {
            var passwordService = new PasswordService();

            List<User> users =
                CreateUsers(passwordService);

            List<Account> accounts =
                CreateAccounts(users);

            List<Transaction> transactions =
                CreateTransactions(accounts);

            // Stop immediately if any integrity rule fails.
            ValidateSeedData(users, accounts, transactions);

            return (users, accounts, transactions);
        }


        // -------------------------------------------------
        // MEMBER 1 - REQUIREMENT 5
        // STEP 5 - SAVE INITIAL DATA TO SQLITE
        // -------------------------------------------------
        //
        // Purpose:
        // Connect the generation and validation methods
        // and save the complete banking dataset.
        //
        // Assignment reference:
        // Assignment 2 Part A - Requirement 5.
        //
        // Lecturer reference:
        // Database-DC-Web lectures - EF Core and SQLite.
        //
        // External references:
        // Microsoft Learn - EF Core Data Seeding
        // https://learn.microsoft.com/en-us/ef/core/modeling/data-seeding
        //
        // Microsoft Learn - EF Core Transactions
        // https://learn.microsoft.com/en-us/ef/core/saving/transactions
        //
        // Design:
        // - Seed only an initially empty database.
        // - Prevent duplicate generation on later runs.
        // - Validate all generated data before saving.
        // - Save related entities using EF Core.
        // - Commit all changes as one transaction.
        // - Roll back automatically if saving fails.
        //
        // Integration dependency:
        // This method must be called after Member 3
        // creates or migrates the database schema.

        public static async Task SeedAsync(BankContext context)
        {
            ArgumentNullException.ThrowIfNull(context);

            // ---------------------------------------------
            // STEP 5A - BEGIN DATABASE TRANSACTION
            // ---------------------------------------------
            //
            // The transaction protects the entire
            // initialization operation from partial saves.

            await using var dbTransaction =
                await context.Database.BeginTransactionAsync();

            // ---------------------------------------------
            // STEP 5B - CHECK WHETHER DATA ALREADY EXISTS
            // ---------------------------------------------
            //
            // Do not insert the demonstration dataset into
            // a database that already contains records.
            //
            // This prevents duplicate seed data when the
            // application starts again.
            //
            // The seeder is intended for an empty database.
            // Existing non-seed data is left untouched.

            bool hasExistingData =
                await context.Users.AnyAsync() ||
                await context.Accounts.AnyAsync() ||
                await context.Transactions.AnyAsync();

            if (hasExistingData)
            {
                // No changes were made.
                // Disposing the transaction is safe.
                return;
            }

            // ---------------------------------------------
            // STEP 5C - GENERATE THE COMPLETE DATASET AND VALIDATE
            // ---------------------------------------------

            // Generate and validate the entire dataset before saving.
            // Reuse the same logic exercised by the unit tests.
            var (users, accounts, transactions) =
                GenerateValidatedData();

            // ---------------------------------------------
            // STEP 5D - REGISTER ENTITIES WITH EF CORE
            // ---------------------------------------------
            //
            // Account.User and Transaction.Account /
            // TargetAccount establish relationships.
            //
            // EF Core will assign generated primary keys
            // and the corresponding foreign keys.

            context.Users.AddRange(users);
            context.Accounts.AddRange(accounts);
            context.Transactions.AddRange(transactions);


            // =====================================================
            // MEMBER 1 + MEMBER 3 - SEEDER INTEGRATION CORRECTION
            // =====================================================
            // Member 1's seeder already registers the complete
            // dataset (20 users, 30 accounts and 500 transactions)
            // using AddRange() earlier in this method.
            //
            // The separate 'admin' variable belonged to Member 3's
            // original seeder and does not exist in this implementation.
            //
            // SaveChangesAsync() persists all registered entities.
            // =====================================================

            await context.SaveChangesAsync();

            // ---------------------------------------------
            // STEP 5F - COMMIT THE TRANSACTION
            // ---------------------------------------------
            //
            // Only commit after every record has been
            // successfully saved.

            await dbTransaction.CommitAsync();
        }

    }
}
